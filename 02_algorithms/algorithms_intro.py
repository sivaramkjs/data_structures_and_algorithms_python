# Algorithms:
#   A sequential set of steps to solve a problem.
#   Most common type of algorithms:
#       1. Recursion
#       2. Sorting
#       3. Dynamic Programming
#       4. Searching + Breadth First Search (BFS) + Depth First Search (DFS)

# Greedy Algorithms:
#   1 .An algorithm is called "Greedy" if it solves an optimization problem with divide and conquer but only selects the
#      best solution at each step i.e., locally optimal solution without backtracking or reconsidering previous solutions.
#   2. While it can generally provide optimal solutions, it could result in suboptimal solutions in some cases.
#   3. Simple, faster and relatively less computing cost.

# Non-Greedy Algorithms:
#   1. An algorithm is called "Non-Greedy" if it solves an optimization problem with divide and conquer and selects the
#      best solution overall i.e., globally optimal solution either by backtracking or reconsidering previous solutions.
#   2. It will try to provide the most optimal solution in most cases.
#   3. Complex, slower and relatively higher computing cost.
#   E.g., Dynamic Programming
