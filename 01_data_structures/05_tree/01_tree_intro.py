# Tree is a hierarchical (non-linear) data structure
# Each element is called a "node".
# root - Top most node in a tree
# parent - Any node with a child node
# child - Any node with a parent node
# siblings - All nodes sharing the same parent node
# leaf - bottom most nodes in a tree

#               1
#             /   \
#           2      3
#         /  \
#       4     5

# root node     -   1
# parent nodes  -   1, 2
# child nodes   -   (2, 3), (4, 5)
# leaf nodes    -   3, 4, 5
# siblings      -   (2, 3), (4, 5)
